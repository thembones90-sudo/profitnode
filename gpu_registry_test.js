"use strict";
const fs=require('fs');
const m=JSON.parse(fs.readFileSync('profitnode_gpu_master_registry_v4.json','utf8'));
const a=JSON.parse(fs.readFileSync('profitnode_gpu_aliases_v4.json','utf8'));
let pass=0,fail=0;
const check=(name,ok)=>{console.log((ok?'PASS':'FAIL')+' - '+name);ok?pass++:fail++};
const by=new Map(m.entries.map(x=>[x.model,x]));
const score=n=>by.get(n)?.score;
const tier=n=>by.get(n)?.tier;
check('master registry version is V4',m.version==='PN_GPU_MASTER_V4_20261004');
check('master registry has 193 GPUs',m.entries.length===193);
check('no duplicate model names',new Set(m.entries.map(x=>x.model)).size===m.entries.length);
check('every entry has brand/model/score/tier/confidence/source',m.entries.every(x=>x.brand&&x.model&&Number.isFinite(x.score)&&x.tier&&x.confidence&&x.source_basis));
check('price/value absent from rating records',m.entries.every(x=>x.price==null&&x.purchasePrice==null&&x.value==null));
check('GT 640 DDR3 and GDDR5 stay distinct',score('GT 640 2GB GDDR5')>score('GT 640 2GB DDR3'));
check('GTX 980 Ti > GTX 980',score('GTX 980 Ti 6GB')>score('GTX 980 4GB'));
check('GTX 980 > GTX 970',score('GTX 980 4GB')>score('GTX 970 4GB'));
check('GTX 780 Ti > GTX 780',score('GTX 780 Ti 3GB')>score('GTX 780 3GB'));
check('R9 Fury X > R9 390',score('R9 Fury X 4GB HBM')>score('R9 390 8GB'));
check('R9 390X > R9 390',score('R9 390X 8GB')>score('R9 390 8GB'));
check('Arc B580 > Arc B570',score('Arc B580 12GB')>score('Arc B570 10GB'));
check('Arc A770 16GB > Arc A750',score('Arc A770 16GB')>score('Arc A750 8GB'));
check('Arc A750 > Arc A580',score('Arc A750 8GB')>score('Arc A580 8GB'));
check('Arc A580 > Arc A380',score('Arc A580 8GB')>score('Arc A380 6GB'));
check('B580 direct 2026 score is 36',score('Arc B580 12GB')===36);
check('B570 direct 2026 score is 31',score('Arc B570 10GB')===31);
check('GTX 1080 Ti > GTX 1080',score('GTX 1080 Ti 11GB')>score('GTX 1080 8GB'));
check('RTX 2060 SUPER > RTX 2060',score('RTX 2060 SUPER 8GB')>score('RTX 2060 6GB'));
check('RTX 3060 Ti > RTX 3060',score('RTX 3060 Ti 8GB GDDR6')>score('RTX 3060 12GB'));
check('RTX 3070 > RTX 3060 Ti',score('RTX 3070 8GB')>score('RTX 3060 Ti 8GB GDDR6'));
check('RTX 3080 > RTX 3070 Ti',score('RTX 3080 10GB')>score('RTX 3070 Ti 8GB'));
check('RTX 4070 SUPER > RTX 4070',score('RTX 4070 SUPER 12GB')>score('RTX 4070 12GB'));
check('RTX 4090 > RTX 4080 SUPER',score('RTX 4090 24GB')>score('RTX 4080 SUPER 16GB'));
check('RTX 5090 > RTX 4090',score('RTX 5090 32GB')>score('RTX 4090 24GB'));
check('RX 580 full > RX 580 2048SP',score('RX 580 8GB')>score('RX 580 2048SP 8GB'));
check('RX 590 > RX 580',score('RX 590 8GB')>score('RX 580 8GB'));
check('RX 5700 XT > RX 5700',score('RX 5700 XT 8GB')>score('RX 5700 8GB'));
check('RX 6700 XT > RX 6600 XT',score('RX 6700 XT 12GB')>score('RX 6600 XT 8GB'));
check('RX 6800 XT > RX 6800',score('RX 6800 XT 16GB')>score('RX 6800 16GB'));
check('RX 7900 XTX > RX 7900 XT',score('RX 7900 XTX 24GB')>score('RX 7900 XT 20GB'));
check('RX 9070 XT > RX 9070',score('RX 9070 XT 16GB')>score('RX 9070 16GB'));
check('RTX 3060 8GB != 12GB',score('RTX 3060 8GB')!==score('RTX 3060 12GB'));
check('RTX 3050 6GB != 8GB',score('RTX 3050 6GB')!==score('RTX 3050 8GB'));
check('RTX 4060 Ti 8GB != 16GB',score('RTX 4060 Ti 8GB')!==score('RTX 4060 Ti 16GB'));
check('aliases include Intel Arc B580',a.aliases['Intel Arc B580']==='Arc B580 12GB');
check('ambiguous GTX 1060 is protected from auto-alias',a.do_not_auto_alias.includes('GTX 1060'));
check('ambiguous RX 580 is protected from auto-alias',a.do_not_auto_alias.includes('RX 580'));
check('mobile patterns excluded',a.excluded_variant_patterns.some(x=>x.includes('Mobile'))&&a.excluded_variant_patterns.some(x=>x.includes('Laptop')));
check('workstation patterns excluded',a.excluded_variant_patterns.some(x=>x.includes('Quadro'))&&a.excluded_variant_patterns.some(x=>x.includes('RTX PRO')));
check('all V4 expansion records have explicit confidence',m.entries.filter(x=>x.rating_method==='PN_GPU_V4_EXPANSION_20261004').every(x=>x.confidence));
check('legacy dual-GPU cards are low confidence',by.get('GTX 690 4GB').confidence==='LOW'&&by.get('GTX TITAN Z 12GB').confidence==='LOW');
check('B580 keeps raw 2026 raster provenance',by.get('Arc B580 12GB').raster_1080p===35.1&&by.get('Arc B580 12GB').raster_1440p===30.3&&by.get('Arc B580 12GB').raster_4k===24.9);
console.log(`\n${pass} passed, ${fail} failed`); if(fail) process.exit(1);
