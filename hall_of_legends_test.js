assert.match(r.achievements.find(a=>a.id==="combined-1").description,/lifetime realized profit/i);
assert.equal(r.achievements.find(a=>a.id==="rig-1").unlockedAt,"2026-10-20","unlocks retain deterministic ledger evidence dates");
assert.ok(r.prestige>0,"high-tier milestones award prestige separately from XP");
