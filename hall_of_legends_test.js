"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const script=fs.readFileSync(path.join(__dirname,"hall_of_legends_extension.js"),"utf8");
const ctx={ROUTES:[],NAV_ICON:{},globalThis:null,Store:{load:()=>({})},convert:(n,from,to)=>from==="EUR"?n:n/117.5,document:{addEventListener(){}},pageHeader:()=>"",escHtml:s=>String(s),render:()=>{}};
ctx.globalThis=ctx;vm.createContext(ctx);vm.runInContext(script,ctx);
const evaluate=ctx.PN_HALL.evaluate;
assert.equal(ctx.PN_HALL.level(0).level,1,"there must never be a level zero");
assert.equal(ctx.PN_HALL.level(100).level,2);
assert.equal(ctx.PN_HALL.level(400).level,3);
const sale=(id,kind,p,c,extra=0)=>({id,saleType:kind,saleState:"COMPLETED",currency:"EUR",buyerPrice:p,originalInvestment:c,additionalCosts:extra,saleDate:"2026-10-20"});
const snapshot=(sales)=>({sales,inventory:[],projects:[],repairs:[]});
let r=evaluate(snapshot([sale("rig1","RIG",350,250,10),sale("part1","COMPONENT",100,40,5)]),ctx.convert);
assert.equal(r.metrics.rigProfit,90);
assert.equal(r.metrics.partProfit,55);
assert.equal(r.metrics.allProfit,145);
assert.equal(r.metrics.revenue,450);
assert.ok(ctx.PN_HALL.level(r.xp).level>1,"historically earned achievements grant a nonstarter level immediately");
assert.equal(r.achievements.length,90,"catalog should contain exactly 90 uniquely identified trophies");
assert.equal(new Set(r.achievements.map(a=>a.id)).size,90,"trophy identities must be unique");
assert.equal(r.metrics.bestRigProfit,90);
assert.equal(r.metrics.bestPartProfit,55);
assert.equal(r.metrics.profitablePartSales,1);
assert.ok(Math.abs(r.metrics.bestROIValue-122.2222222)<0.0001);
assert.equal(r.achievements.find(a=>a.id==="partrecord-3").unlocked,true);
assert.equal(r.achievements.find(a=>a.id==="roirecord-4").unlocked,true);
assert.equal(r.metrics.rigSales,1);
assert.equal(r.metrics.partSales,1);
assert.equal(r.achievements.find(a=>a.id==="combined-1").unlocked,true);
assert.equal(r.xp,evaluate(snapshot([sale("rig1","RIG",350,250,10),sale("part1","COMPONENT",100,40,5)]),ctx.convert).xp,"recomputation must not double-award XP");
r=evaluate(snapshot([{...sale("gift","RIG",0,250),disposition:"GIFT"},{...sale("pending","COMPONENT",200,10),saleState:"PENDING"},sale("loss","COMPONENT",10,100)]),ctx.convert);
assert.equal(r.metrics.allProfit,-90);
assert.equal(r.metrics.rigSales,0);
assert.equal(r.metrics.partSales,1);
r=evaluate(snapshot([{...sale("unknown","RIG",500,200),originalInvestment:null},sale("valid","COMPONENT",100,40)]),ctx.convert);
assert.equal(r.metrics.rigProfit,0);
assert.equal(r.metrics.partProfit,60);
assert.equal(r.metrics.revenue,600);
assert.equal(r.unverified.length,1);
r=evaluate(snapshot([{...sale("rsd","COMPONENT",11750,5875),currency:"RSD"}]),ctx.convert);
assert.equal(r.metrics.partProfit,50);
r=evaluate({...snapshot([]),projects:[{status:"COMPLETED",purpose:"FAMILY_GIFT"}],inventory:Array(10).fill({})},ctx.convert);
assert.equal(r.achievements.find(a=>a.id==="generous").unlocked,true);
assert.equal(r.achievements.find(a=>a.id==="stock-1").unlocked,true);
r=evaluate({...snapshot([]),inventory:[{source:"FLEA_MARKET"},{source:"SHOP"}]},ctx.convert);
assert.equal(r.metrics.fleaMarketCount,1);
assert.equal(r.achievements.find(a=>a.id==="fleamarket-1").unlocked,true);
assert.equal(ctx.ROUTES.some(x=>x.key==="hall"),true);
ctx.saleDerived=s=>({totalCost:s.originalInvestment+(s.additionalCosts||0)+20,profit:s.buyerPrice-s.originalInvestment-(s.additionalCosts||0)-20});
r=evaluate(snapshot([sale("shipping","RIG",350,250,10)]),ctx.convert);
assert.equal(r.metrics.rigProfit,70,"outgoing shipping must reduce achievement profit");
assert.equal(r.metrics.revenue,350,"shipping must not reduce gross revenue");
delete ctx.saleDerived;
r=evaluate(snapshot([{...sale("usd","RIG",500,300),currency:"USD"}]),ctx.convert);
assert.equal(r.metrics.revenue,0,"unsupported USD must not be converted at 1:1");
assert.equal(r.unverified.length,1);
ctx.Store.load=()=>snapshot([sale("visual","RIG",350,250,10)]);
const markup=ctx.ROUTES.find(x=>x.key==="hall").render();
assert.match(markup,/HALL OF LEGENDS/);
assert.match(markup,/EMPIRE OF MACHINES/i);
assert.match(markup,/RIG NET PROFIT/);
assert.match(markup,/THE CHRONICLE/);
assert.match(markup,/ACHIEVEMENTS/);
console.log("Hall of Legends regression tests passed");
