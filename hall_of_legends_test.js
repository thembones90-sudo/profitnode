assert.equal(r.metrics.rigSales,0);
assert.equal(r.metrics.partSales,1);
r=evaluate(snapshot([
 {...sale("peak","RIG",250,100),saleDate:"2026-10-01"},
 {...sale("later-loss","RIG",10,100),saleDate:"2026-10-02"}
]),ctx.convert);
assert.equal(r.metrics.rigProfit,60);
assert.equal(r.achievements.find(a=>a.id==="combined-1").unlocked,true,"an earned cumulative trophy must survive a later loss");
