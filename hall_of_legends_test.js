"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const script=fs.readFileSync(path.join(__dirname,"hall_of_legends_extension.js"),"utf8");
const ctx={ROUTES:[],NAV_ICON:{},globalThis:null,Store:{load:()=>({})},convert:(n,from,to)=>from==="EUR"?n:n/117.5,document:{addEventListener(){}},pageHeader:()=>"",escHtml:s=>String(s),render:()=>{}};
